#!/usr/bin/env python3
"""Generate current-context views from canonical STATE/BACKLOG, never a second state."""
import argparse
from pathlib import Path
import yaml

ROOT=Path(__file__).resolve().parents[1]

def render(root):
    state=yaml.safe_load((root/'context/roadmap/STATE.yaml').read_text())
    backlog=yaml.safe_load((root/'context/roadmap/BACKLOG.yaml').read_text())
    tasks={item['id']:item for item in backlog['tasks']}
    current={
      'schema_version':1,'generated':True,
      'sources':['context/roadmap/STATE.yaml','context/roadmap/BACKLOG.yaml'],
      'entrypoint':'START_HERE.md','updated_at':state['updated_at'],
      'canonical_branch':state['canonical_roadmap_branch'],
      'repository_head':{'resolution':'git rev-parse HEAD; git rev-parse origin/main',
                         'note':'Resolve at read time; never store a self-referencing or placeholder commit'},
      'application_baseline':state['code_baseline'],
      'production':state['production'],
      'current_work':{'activity':state['current_activity'],'next_task':state['next_task'],
         'ready_tasks':state['ready_tasks'],
         'task_statuses':{key:tasks[key]['status'] for key in sorted(tasks)}},
      'server_facts':state.get('server_facts',{'status':'awaiting_collection','snapshot':None}),
      'sysadmin_restore':state['sysadmin_restore'],
      'deferred_platform':state['deferred_platform'],
    }
    checkpoint=(f'# USTAR current checkpoint — generated\n\n'
      f'Entry point and reading order: [START_HERE](../../START_HERE.md).\n'
      f'Canonical state: [STATE](../../context/roadmap/STATE.yaml).\n'
      f'Machine view: [current.yaml](../../context/current.yaml).\n\n'
      f'Updated: {state["updated_at"]}. Next task: {state["next_task"]}.\n'
      f'Application baseline: {state["code_baseline"]["commit"]}.\n'
      'This is not a deployment receipt. Do not edit this generated file.\n')
    return {'context/current.yaml':'# Generated by scripts/build_current_context.py. Edit STATE/BACKLOG.\n'+yaml.safe_dump(current,allow_unicode=True,sort_keys=False),
            '.codex/checkpoints/CURRENT.md':checkpoint}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=ROOT)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for relative,content in render(args.root).items():
        path=args.root/relative
        if any(p.is_symlink() for p in [path,*path.parents]):
            raise ValueError('symlink_output_forbidden')
        if args.check:
            if not path.is_file() or path.read_text()!=content:
                raise ValueError('stale_generated_context: '+relative)
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(content)
    print('CURRENT_CONTEXT_OK')

if __name__=='__main__':
    main()
