#!/usr/bin/env python3
"""Generate code-backed design tokens and capability reference inventory without PHP execution."""
import argparse
import hashlib
from pathlib import Path
import re
import yaml

ROOT=Path(__file__).resolve().parents[1]

def render(root):
    token_path='moodle/theme/ustar/scss/_tokens.scss'
    raw=(root/token_path).read_bytes()
    text=raw.decode()
    sections={}
    for selector in (':root','html[data-ustar-theme="dark"]'):
        match=re.search(re.escape(selector)+r'\s*{([^}]+)}',text)
        if not match:
            raise ValueError('design_token_structure_changed')
        sections[selector]=dict(re.findall(r'(--[a-z0-9-]+)\s*:\s*([^;]+);',match[1]))
    lib=(root/'moodle/theme/ustar/lib.php').read_text()
    layers=['moodle/theme/ustar/scss/'+name for name in re.findall(r"__DIR__\s*\.\s*'/scss/([^']+)'",lib)]
    tokens={'schema_version':1,'generated':True,'source':token_path,
      'source_sha256':hashlib.sha256(raw).hexdigest(),'values':sections,'theme_layer_order':layers,
      'limits':['Declared source tokens, not computed styles; later layers and page CSS may override them',
                'Academy tokens are separate from the server-console UI in PR103']}
    access='moodle/local/ustar/db/access.php'
    source=(root/access).read_text()
    matches=list(re.finditer(r"^\s*['\"](local/ustar:[A-Za-z_0-9]+)['\"]\s*=>\s*\[",source,re.M))
    if not matches:
        raise ValueError('capability_structure_changed')
    php={str(p.relative_to(root)):p.read_text() for p in (root/'moodle/local/ustar').rglob('*.php')}
    capabilities=[]
    for i,match in enumerate(matches):
        name=match[1]
        block=source[match.end():matches[i+1].start() if i+1<len(matches) else len(source)]
        captype=re.search(r"'captype'\s*=>\s*'(read|write)'",block)
        context=re.search(r"'contextlevel'\s*=>\s*(CONTEXT_[A-Z_]+)",block)
        archetypes=re.search(r"'archetypes'\s*=>\s*\[([^\]]*)\]",block,re.S)
        if not captype or not context or not archetypes:
            raise ValueError('unsupported_capability_definition: '+name)
        risk=re.search(r"'riskbitmask'\s*=>\s*([^,]+)",block)
        direct=re.compile(r"(?:has_capability|require_capability)\s*\(\s*['\"]"+re.escape(name)+r"['\"]")
        capabilities.append({'capability':name,'captype':captype[1],'contextlevel':context[1],
          'risk_constants':re.findall(r'RISK_[A-Z_]+',risk[1]) if risk else [],
          'declared_archetypes':dict(re.findall(r"'([^']+)'\s*=>\s*(CAP_[A-Z_]+)",archetypes[1])),
          'literal_reference_paths':sorted(path for path,code in php.items() if path!=access and name in code),
          'direct_check_paths':sorted(path for path,code in php.items() if direct.search(code))})
    matrix={'schema_version':1,'generated':True,'definition_source':access,
      'definition_sha256':hashlib.sha256((root/access).read_bytes()).hexdigest(),
      'effective_production_role_bindings':'not_measured',
      'limits':['Literal references are navigation aids, not proof of a complete authorization path',
                'Dynamic capability names, actor/scope/revision/sesskey checks require service and endpoint review',
                'Declared archetypes do not prove actual grants in the production database'],
      'capabilities':capabilities}
    header='# Generated by scripts/build_agent_inventory.py; source code remains authoritative.\n'
    return {'context/design/tokens.yaml':header+yaml.safe_dump(tokens,allow_unicode=True,sort_keys=False),
            'context/architecture/access_matrix.yaml':header+yaml.safe_dump(matrix,allow_unicode=True,sort_keys=False)}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=ROOT)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for relative,content in render(args.root).items():
        path=args.root/relative
        if any(p.is_symlink() for p in [path,*path.parents]):
            raise ValueError('symlink_inventory_output')
        if args.check:
            if not path.is_file() or path.read_text()!=content:
                raise ValueError('stale_agent_inventory: '+relative)
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(content)
    print('AGENT_INVENTORY_OK')

if __name__=='__main__':main()
