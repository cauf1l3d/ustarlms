const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {JSDOM}=require('jsdom');
const dir=path.resolve(__dirname,'../../moodle/local/ustar/course_studio');
const dom=new JSDOM('',{runScripts:'outside-only',url:'https://academy.example/studio/'}),w=dom.window;
w.TextEncoder=TextEncoder;w.TextDecoder=TextDecoder;
for(const f of ['model.js','rich.js'])w.eval(fs.readFileSync(dir+'/'+f,'utf8'));
if(fs.existsSync(dir+'/pdf.js'))w.eval(fs.readFileSync(dir+'/pdf.js','utf8'));
assert(w.StudioPDF,'PDF import/export adapter must be available');
const P=w.StudioPDF;
const items=[{str:'Привет',transform:[1,0,0,12,20,700],width:40},{str:'мир',transform:[1,0,0,12,65,700],hasEOL:true},{str:'Вторая строка',transform:[1,0,0,12,20,680]}];
assert.equal(P.textLines(items).join('\n'),'Привет мир\nВторая строка');
const c=P.fromPages(['<script>alert(1)</script>\nТекст',''], 'Учебник.pdf');
assert.equal(c.data.pages.length,2);assert.equal(c.data.title,'Учебник');
assert(c.data.pages[0].html.includes('&lt;script&gt;'));assert(!c.data.pages[0].html.includes('<script>'));
assert(c.data.pages[1].source_text.includes('2'));assert.equal(w.RCModel.validateCourse(c).length,0);
assert.throws(()=>P.fromPages(['','  '],'scan.pdf'),/текстового слоя/);
assert.throws(()=>P.fromPages(Array(201).fill('text'),'large.pdf'),/200/);
assert.throws(()=>P.fromPages(['x'.repeat(2000001)],'large.pdf'),/символ/);
assert.equal(P.fromPages(['text'],'я'.repeat(280)+'.pdf').data.title.length,255);
assert.throws(()=>P.fromPages(['я'.repeat(1100000)],'large.pdf'),/экран|страниц/);
const print=P.printHTML(c,()=> 'blob:fixture');
const doc=new JSDOM(print).window.document;
assert.equal(doc.querySelectorAll('script,iframe,object').length,0);
assert.equal(doc.querySelectorAll('.lesson').length,2);
assert(doc.body.textContent.includes('Учебник'));assert(doc.body.textContent.includes('<script>alert(1)</script>'));
assert(print.includes('@page'));assert(print.includes('break-before:page'));
c.data.pages[0].html='<img src="assets/x.png" onerror="alert(1)"><a href="javascript:alert(1)">x</a>';
const safe=new JSDOM(P.printHTML(c,()=> 'blob:fixture')).window.document;
assert(!safe.querySelector('[onerror]'));assert(!safe.querySelector('a[href^="javascript:"]'));
dom.window.close();console.log('COURSE_STUDIO_PDF_OK Cyrillic lines escaping page limits scan print safety');
