#!/usr/bin/env python3
"""Build exact-Git operator tooling with the immutable, already verified RC830 payload."""
import argparse
import gzip
import hashlib
import io
import json
from pathlib import Path
import re
import subprocess
import tarfile
import zipfile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
PAYLOAD_COMMIT = '830d3703e2ffa2f9864900c0d0c58f60049cb0c2'
RC_HASH = 'a67a08d8e5509c580043a6752e73964cb8aed72c5d1732647a9d3c2e2379113e'
MODULES = ('connect_academy_installer', 'connect_readiness', 'production_patch_readiness',
           'production_patch_upgrade', 'production_patch_switch_preflight',
           'lab_cold_checkpoint', 'lab_patch_upgrade', 'lab_patch_candidate')


def build(commit, output, *, repo=ROOT):
    if not re.fullmatch(r'(?:HEAD|[a-f0-9]{40})', commit):
        raise ValueError('exact_commit_required')
    def git(*args):
        return subprocess.check_output(['git', '-C', str(repo), *args], stderr=subprocess.DEVNULL)
    sha = git('rev-parse', '--verify', commit + '^{commit}').decode().strip()
    # The source RC is regenerated by its exact builder in an isolated temporary
    # Git export. No imports from an operator's dirty working tree enter the zip.
    import tempfile
    with tempfile.TemporaryDirectory(prefix='ustar-connect-installer-') as temporary:
        temporary = Path(temporary)
        helper = git('show', PAYLOAD_COMMIT + ':scripts/infra/build_connect_academy_release.py')
        # Existing builder needs its build_readiness sibling. Execute the frozen
        # build functions with ROOT bound to an export of those two source files.
        infra = temporary / 'scripts/infra'
        infra.mkdir(parents=True)
        (infra / 'build_connect_academy_release.py').write_bytes(helper)
        (infra / 'build_connect_readiness.py').write_bytes(
            git('show', PAYLOAD_COMMIT + ':scripts/infra/build_connect_readiness.py'))
        namespace = {'__file__': str(infra / 'build_connect_academy_release.py'), '__name__': 'frozen_rc_builder'}
        exec(compile(helper, namespace['__file__'], 'exec'), namespace)
        rc = namespace['build'](PAYLOAD_COMMIT, temporary / 'rc', repo=repo)
        if hashlib.sha256(rc.read_bytes()).hexdigest() != RC_HASH:
            raise ValueError('frozen_rc_hash')
        with tarfile.open(rc) as archive:
            contents = {m.name: archive.extractfile(m).read() for m in archive if m.isfile()}
    reference = json.loads(contents['manifest.json'])['reference']
    schema_fields = {table.attrib['NAME']: {field.attrib['NAME']: {
        'type': field.attrib['TYPE'], 'length': field.attrib.get('LENGTH'),
        'notnull': field.attrib.get('NOTNULL') == 'true'} for field in table.findall('./FIELDS/FIELD')}
        for table in ET.fromstring(contents['payload/local/ustar/db/install.xml']).findall('.//TABLE')}
    files = {name: raw for name, raw in contents.items() if name.startswith('payload/')}
    files['reference.json'] = (json.dumps(reference, sort_keys=True) + '\n').encode()
    files['__main__.py'] = b'from connect_academy_installer import main\nraise SystemExit(main())\n'
    for name in MODULES:
        files[name + '.py'] = git('show', sha + ':scripts/infra/' + name + '.py')
    files['production_manifest.py'] = git('show', sha + ':scripts/production_manifest.py')
    manifest = {'schema': 1, 'tool_commit': sha, 'payload_commit': PAYLOAD_COMMIT,
        'original_source_rc_sha256': RC_HASH, 'schema_fields': schema_fields,
        'files': {name: hashlib.sha256(raw).hexdigest() for name, raw in sorted(files.items())}}
    files['INSTALL_MANIFEST.json'] = (json.dumps(manifest, sort_keys=True, indent=2) + '\n').encode()
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, raw in sorted(files.items()):
            entry = zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0))
            entry.compress_type = zipfile.ZIP_DEFLATED
            entry.external_attr = 0o100644 << 16
            archive.writestr(entry, raw)
    controller = stream.getvalue()
    guide = git('show', sha + ':context/runtime/connect_academy_install_20261020.md')
    package = {'update.pyz': controller, 'INSTRUCTION.md': guide,
               'TOOL_COMMIT': (sha + '\n').encode(), 'PAYLOAD_COMMIT': (PAYLOAD_COMMIT + '\n').encode()}
    package['SHA256SUMS'] = ''.join(hashlib.sha256(raw).hexdigest() + '  ' + name + '\n'
                                   for name, raw in sorted(package.items())).encode()
    result = io.BytesIO()
    with gzip.GzipFile(fileobj=result, filename='', mode='wb', mtime=0, compresslevel=9) as compressed:
        with tarfile.open(fileobj=compressed, mode='w', format=tarfile.USTAR_FORMAT) as archive:
            for name, raw in sorted(package.items()):
                member = tarfile.TarInfo(name)
                member.size, member.mode, member.mtime = len(raw), 0o644, 0
                archive.addfile(member, io.BytesIO(raw))
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    target = output / ('ustar-connect-install-' + sha[:8] + '.tar.gz')
    target.write_bytes(result.getvalue())
    target.chmod(0o644)
    digest = hashlib.sha256(target.read_bytes()).hexdigest()
    target.with_suffix(target.suffix + '.sha256').write_text(digest + '  ' + target.name + '\n')
    print(json.dumps({'archive': str(target), 'sha256': digest, 'tool_commit': sha,
        'payload_commit': PAYLOAD_COMMIT, 'update_pyz_sha256': hashlib.sha256(controller).hexdigest()}))
    return target


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--commit', default='HEAD')
    parser.add_argument('--output-dir', required=True)
    args = parser.parse_args()
    build(args.commit, args.output_dir)
